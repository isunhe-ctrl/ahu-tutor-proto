  // 简单可复现的洗牌（按种子），使每次加载选项顺序稳定、且正确答案位置不固定
  function shuffle(arr, seed) {
    var s = seed >>> 0;
    function rnd() { s = (s + 0x6D2B79F5) >>> 0; var t = s; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }
    var a = arr.slice(), i, j, tmp;
    for (i = a.length - 1; i > 0; i--) { j = Math.floor(rnd() * (i + 1)); tmp = a[i]; a[i] = a[j]; a[j] = tmp; }
    return a;
  }


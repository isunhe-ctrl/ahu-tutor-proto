    var m = global.COURSE_MODULES && global.COURSE_MODULES.filter(function (x) { return x.id === id; })[0];
    if (!m) return;
    // 已有课程脚本(course.js)提供的精选题库则不再用模板生成，保证题目科学性与一致性
    if (m.quizzes && m.quizzes.length) return;
    var arr = [];
    topics[id].forEach(function (topic, ti) {
      var opts = (generic[id] && generic[id][ti]) ? generic[id][ti].slice()
        : ['核对该知识点在系统中的作用', '核对其输入与输出是否有效', '确认其与相关环节的关联', '出现与预期不符却无报警', '做针对性现场验证'];
      stems.forEach(function (stem, vi) {
        var correct = opts[vi];                                  // 第 vi 题的参考答案
        var others = opts.filter(function (_, i) { return i !== vi; }); // 其余 4 项作干扰项来源
        var start = vi % others.length;                          // 轮转起点：富余选项在组内不同题间轮换复用
        var distractors = [others[start], others[(start + 1) % 4], others[(start + 2) % 4]];
        var options = shuffle([correct].concat(distractors), ti * 31 + vi * 7 + 1); // 共 4 个选项
        var answer = options.indexOf(correct);
        arr.push([stem.replace('{topic}', topic), options, answer]);
      });
    });
    m.quizzes = arr; // 每个模块固定 50 题（10 知识点 × 5 变式），由 course_ui.js 随机抽 5 题
